#!/usr/bin/env node
/**
 * Regenerate the "solid fills keep white text" block in globals.css.
 *
 * Light mode is built by reinterpreting the dashboards' dark utility classes —
 * `.dash-light .text-white` turns white text near-black, which is right on a
 * pale surface and wrong on a saturated button. That was patched with a
 * hand-written allowlist of the fills someone had noticed, which is a list that
 * goes stale the moment anyone adds a button: an audit found five families
 * already uncovered (bg-blue-600, bg-blue-500, bg-red-500, bg-amber-500,
 * bg-teal-600), each rendering near-black text on a saturated fill.
 *
 * So the block is generated over the whole palette instead of curated. Run:
 *
 *   node scripts/gen-dash-fills.mjs          # rewrite the block
 *   node scripts/gen-dash-fills.mjs --check  # fail if it is out of date
 *
 * `[class~="…"]` matches a whitespace-separated whole class, so `bg-sky-500`
 * matches the solid fill but NOT the `bg-sky-500/15` tint — tints are pale in
 * light mode and must keep their dark text.
 */
import fs from "node:fs";

const CSS = "src/app/globals.css";
const START = "/* >>> generated by scripts/gen-dash-fills.mjs — do not edit by hand */";
const END = "/* <<< end generated block */";

// Every family used as a solid fill anywhere in the app, plus the brand ramp.
const FAMILIES = [
  "medical", "slate", "gray", "zinc", "neutral", "stone",
  "red", "orange", "amber", "yellow", "lime", "green", "emerald", "teal",
  "cyan", "sky", "blue", "indigo", "violet", "purple", "fuchsia", "pink", "rose",
];
// 500 and up is where a fill is dark enough that white text is the readable
// choice; below that the fill is pale and the near-black override is correct.
const SHADES = [500, 600, 700, 800, 900, 950];

function block() {
  const fills = [];
  for (const f of FAMILIES) for (const s of SHADES) fills.push(`bg-${f}-${s}`);

  // Same element (`<button class="bg-medical-600 text-white">`) and descendant
  // (`<div class="bg-medical-600"><span class="text-white">`). Both occur.
  const selectors = fills.flatMap((f) => [
    `.dash-light [class~="${f}"].text-white`,
    `.dash-light [class~="${f}"] .text-white`,
  ]);

  return [
    START,
    "/* Solid saturated fills keep white text in light mode. Generated over the",
    "   whole palette so a new button can never silently render dark-on-dark;",
    "   `[class~=]` matches the whole class, so tints like bg-sky-500/15 are not",
    "   caught and keep their dark text. Regenerate with the script above. */",
    selectors.join(",\n"),
    " {\n  color: #ffffff !important;\n}",
    END,
  ].join("\n");
}

const css = fs.readFileSync(CSS, "utf8");
const next = block();

const has = css.includes(START) && css.includes(END);
const current = has ? css.slice(css.indexOf(START), css.indexOf(END) + END.length) : null;

if (process.argv.includes("--check")) {
  if (current === next) {
    console.log("dash fill block is up to date.");
    process.exit(0);
  }
  console.error(has ? "dash fill block is STALE — run: node scripts/gen-dash-fills.mjs" : "dash fill block is MISSING.");
  process.exit(1);
}

if (!has) {
  console.error(`Markers not found in ${CSS}. Add them, or paste the block manually.`);
  process.exit(1);
}
fs.writeFileSync(CSS, css.slice(0, css.indexOf(START)) + next + css.slice(css.indexOf(END) + END.length));
console.log(`Wrote ${FAMILIES.length * SHADES.length * 2} selectors to ${CSS}.`);
